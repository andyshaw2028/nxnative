#!/usr/bin/env python3
"""Preprocess BOTW 1.9.0 shader inputs on Windows so the full RomFS need not be uploaded to the Mac runner.

Run from the nxnative repository root:
  python scripts/preprocess_botw_shaders.py C:\\zelda_work\\romfs C:\\zelda_work\\exefs\\main C:\\zelda_work\\shader_prebuilt C:\\zelda_work\\botw_shader_prebuilt.zip

The ZIP contains only pkg/*.bin and tables/*.tsv generated by shader_split.py; it does not include RomFS, ExeFS, or prod.keys.
"""
from __future__ import annotations

import argparse
import os
from pathlib import Path
import subprocess
import sys
import zipfile


GAME_ID = "01007EF00011E000"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("romfs", help="full extracted BOTW 1.9.0 RomFS directory")
    ap.add_argument("main", help="extracted ExeFS/main NSO file")
    ap.add_argument("work_dir", help="directory for generated pkg/ and tables/")
    ap.add_argument("zip_out", help="output ZIP path for the prebuilt shader bundle")
    ap.add_argument("--jobs", type=int, default=max(2, os.cpu_count() or 4), help="parallel shader scan workers")
    a = ap.parse_args()

    here = Path(__file__).resolve()
    repo = here.parent.parent
    romfs = Path(a.romfs).resolve()
    main_nso = Path(a.main).resolve()
    work = Path(a.work_dir).resolve()
    zip_out = Path(a.zip_out).resolve()
    if not (repo / "dm/gfx/tools/shader_split.py").is_file():
        raise SystemExit("[ERROR] Run this script from a complete nxnative repository checkout.")
    for p in (romfs / "System/Version.txt", romfs / "Pack/Bootup_Graphics.pack", main_nso):
        if not p.is_file():
            raise SystemExit(f"[ERROR] Required input is missing: {p}")
    version = (romfs / "System/Version.txt").read_text(errors="replace").strip()
    if version != "1.9.0":
        raise SystemExit(f"[ERROR] Expected BOTW 1.9.0 RomFS, found Version.txt={version!r}.")

    pkg = work / "pkg"
    tables = work / "tables"
    if work.exists():
        import shutil
        shutil.rmtree(work)
    pkg.mkdir(parents=True)
    tables.mkdir(parents=True)
    env = dict(os.environ, DM_GAME=GAME_ID, J=str(max(1, a.jobs)))
    cmd = [
        sys.executable, str(repo / "dm/gfx/tools/shader_split.py"),
        str(romfs), str(main_nso), str(pkg),
        str(tables / "shader_map.tsv"),
        str(tables / "shader_facts.tsv"),
        str(tables / "shader_pairs.tsv"),
    ]
    print("[1/3] Scanning the full local BOTW 1.9.0 RomFS and ExeFS/main for shaders.", flush=True)
    print("Command:", subprocess.list2cmdline(cmd), flush=True)
    subprocess.run(cmd, cwd=repo, env=env, check=True)

    bins = sorted(pkg.glob("*.bin"))
    map_path = tables / "shader_map.tsv"
    facts_path = tables / "shader_facts.tsv"
    pairs_path = tables / "shader_pairs.tsv"
    for p in (map_path, facts_path, pairs_path):
        if not p.is_file() or p.stat().st_size == 0:
            raise SystemExit(f"[ERROR] Shader split did not produce a non-empty table: {p}")
    rows = sum(1 for line in map_path.open(encoding="utf-8", errors="replace") if line.strip() and not line.startswith("#") and not line.startswith("package\t"))
    if len(bins) == 0 or rows < 1000:
        raise SystemExit(f"[ERROR] Shader output looks incomplete: package files={len(bins)}, shader-map rows={rows}; refusing to create a bundle.")
    print(f"[2/3] Validated {len(bins)} package files and {rows} shader-map rows.", flush=True)

    zip_out.parent.mkdir(parents=True, exist_ok=True)
    if zip_out.exists():
        zip_out.unlink()
    with zipfile.ZipFile(zip_out, "w", allowZip64=True) as z:
        for p in sorted(work.rglob("*")):
            if not p.is_file():
                continue
            rel = p.relative_to(work).as_posix()
            compression = zipfile.ZIP_STORED if p.suffix == ".bin" else zipfile.ZIP_DEFLATED
            z.write(p, rel, compress_type=compression, compresslevel=1 if compression == zipfile.ZIP_DEFLATED else None)
    with zipfile.ZipFile(zip_out, "r") as z:
        bad = z.testzip()
        if bad:
            raise SystemExit(f"[ERROR] ZIP integrity check failed at {bad}")
        names = z.namelist()
        if any(Path(n).name.lower() == "prod.keys" for n in names) or any(n.startswith("RomFS/") or n.startswith("ExeFS/") for n in names):
            raise SystemExit("[ERROR] Refusing a bundle that contains keys or game files.")
    print(f"[3/3] Created {zip_out} ({zip_out.stat().st_size:,} bytes).", flush=True)
    print("Upload this ZIP to a private file host, then set GitHub Actions secret BOTW_SHADER_ZIP_URL to its download URL.", flush=True)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
